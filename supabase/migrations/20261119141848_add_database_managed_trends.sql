
create table if not exists public.trends (
  id bigint generated by default as identity primary key,
  category text not null,
  keyword text not null unique,
  post_count bigint not null default 0 check (post_count >= 0),
  rank integer not null default 0,
  is_active boolean not null default true,
  updated_at timestamptz not null default now()
);
alter table public.trends enable row level security;
grant select on public.trends to anon, authenticated;
drop policy if exists "Trends are publicly readable" on public.trends;
create policy "Trends are publicly readable" on public.trends for select to anon, authenticated using (is_active);
